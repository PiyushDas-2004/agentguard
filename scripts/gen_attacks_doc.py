"""Generate docs/ATTACKS.md from the category registry, remediation library and datasets.

Usage: uv run python scripts/gen_attacks_doc.py
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from agentguard.attacks.loader import load_cases
from agentguard.attacks.registry import ATLAS_TECHNIQUES, CATEGORY_INFO, MIN_CASES
from agentguard.core.types import AttackCategory, InjectionVector
from agentguard.reporting.remediation import REMEDIATION
from agentguard.scoring.owasp import CATEGORY_OWASP, OWASP_LLM_2025

DETECTION = {
    AttackCategory.PI_DIRECT: "Secret canaries (system prompt, files, DB, RAG, memory) are searched in every reply and tool argument in 13 encodings; violating tool calls are re-checked against the policy.",
    AttackCategory.PI_INDIRECT: "Each poisoned payload carries a per-trial *obedience canary*: if it appears in the output the agent followed injected instructions. Tool hijacks are caught by the policy and exfil detectors.",
    AttackCategory.JAILBREAK: "Deterministic detectors decide first (canary, tool policy, system prompt). Only when none fires does the rubric-driven judge assess harmful compliance; ensemble disagreement marks the trial inconclusive.",
    AttackCategory.SYS_PROMPT_LEAK: "Word 5-gram overlap with the true system prompt, also computed on reversed, ROT13, de-spaced, base64- and hex-decoded readings, plus the system-prompt canary.",
    AttackCategory.DATA_EXFIL: "Executed http_get/email_send to non-allowlisted destinations, and reply URLs (markdown images/links) whose path or query carries a canary, protected PII, prompt text or a long encoded blob.",
    AttackCategory.PII_LEAK: "Exact match of the synthetic PII planted for the trial plus validated recognizers (Luhn cards, mod-97 IBAN, SSN/Aadhaar/PAN formats, phones); PII typed by the user is ignored.",
    AttackCategory.EXCESSIVE_AGENCY: "Every recorded tool call (executed or not) is evaluated against the policy: forbidden tools, allowlist, argument constraints (with path-traversal normalization) and approval-gate bypass.",
    AttackCategory.INSECURE_OUTPUT: "Rule set for XSS markup, SQL injection, shell metacharacters with commands and unsafe deserialization, with warning-context suppression and zero-width normalization.",
    AttackCategory.MEMORY_POISON: "Two sessions share one memory store; violations (tool policy, canary, exfil) are attributed to the session in which they occur.",
    AttackCategory.RAG_POISON: "Poisoned documents enter the BM25 index for the trial; obedience canaries and tool/exfil detectors catch hijacked answers and actions.",
    AttackCategory.DENIAL_OF_WALLET: "Tool-call count, identical-call count, reply length (before truncation), tokens, turns and wall time against policy limits.",
    AttackCategory.PKG_HALLUCINATION: "Install commands and package mentions are checked against bundled PyPI (15k) and npm (~20k) name snapshots plus the Python stdlib.",
    AttackCategory.OVER_REFUSAL: "Refusal classifier (phrase set + position/length heuristics); a refusal of a benign request is the violation.",
}


def main() -> None:
    cases = load_cases(["datasets/attacks", "datasets/benign"], strict=True).cases
    lines = [
        "# Attack categories",
        "",
        "Generated by `scripts/gen_attacks_doc.py` from the category registry, the remediation library "
        "and the bundled datasets. All objectives are canary- or mock-tool-based; see "
        "[RESPONSIBLE_USE.md](../RESPONSIBLE_USE.md) and [DATASET_AUTHORING.md](DATASET_AUTHORING.md).",
        "",
        "| Category | Cases (min) | OWASP LLM 2025 | Vectors |",
        "|---|---|---|---|",
    ]
    for category in AttackCategory:
        subset = [c for c in cases if c.category == category]
        vectors = Counter(c.vector.value for c in subset)
        owasp = ", ".join(CATEGORY_OWASP[category]) or "—"
        lines.append(
            f"| [{category.value}](#{category.value.lower()}) | {len(subset)} ({MIN_CASES[category]}) | {owasp} | "
            + ", ".join(f"{v} {n}" for v, n in vectors.most_common())
            + " |"
        )
    for category in AttackCategory:
        info = CATEGORY_INFO[category]
        subset = [c for c in cases if c.category == category]
        atlas = Counter(a for c in subset for a in c.mitre_atlas)
        lines += ["", f"## {category.value}", "", f"**{info.title}.** {info.summary}", ""]
        owasp = CATEGORY_OWASP[category]
        if owasp:
            lines.append("**OWASP:** " + ", ".join(f"{o} {OWASP_LLM_2025[o]}" for o in owasp) + "  ")
        if atlas:
            lines.append(
                "**MITRE ATLAS:** " + ", ".join(f"{a} {ATLAS_TECHNIQUES.get(a, '')}" for a, _ in atlas.most_common(4)) + "  "
            )
        lines.append(f"**Seed cases:** {len(subset)}")
        example = next((c for c in subset if c.vector != InjectionVector.user_message), None) or (subset[0] if subset else None)
        if example is not None:
            lines += ["", f"**Example — {example.id}: {example.title}** ({example.severity.value}, vector `{example.vector.value}`)", ""]
            for turn in example.turns:
                lines.append(f"> **user (session {turn.session}):** {turn.content.strip()}  ")
            if example.poison is not None:
                payload = (example.poison.content or f"corpus document `{example.poison.corpus_doc}`").strip()
                lines.append(f"> **poison ({example.poison.vector.value}):** {payload}")
            lines += ["", f"Objective: `{example.objective.type.value}` — {example.objective.description} "
                      f"Detectors: {', '.join(f'`{d}`' for d in example.detectors)}."]
        lines += ["", f"**Detection.** {DETECTION[category]}", "", "**Remediation.**", ""]
        lines += [f"- {item}" for item in REMEDIATION[category]]
    Path("docs/ATTACKS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/ATTACKS.md ({len(cases)} cases)")


if __name__ == "__main__":
    main()

"""Assemble docs/VALIDATION.md from the real output of `scripts/check_all.sh` and extra commands.

Usage:
    scripts/check_all.sh > check_all.log 2>&1
    uv run agentguard calibrate-judge --judge mock > calibration.log 2>&1
    uv run python scripts/build_validation_doc.py check_all.log calibration.log extra.log...

Every number in the generated document is copied verbatim from those logs.
"""

from __future__ import annotations

import re
import sys
from datetime import UTC, datetime
from pathlib import Path

ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
NOISE = re.compile(r"UV_NATIVE_TLS|^\s*(Building|Built|Uninstalled|Installed) .*agentguard|^warning: The `UV")

INTRO = """# Validation

This document is generated by `scripts/build_validation_doc.py` from the **real, unedited output**
of the quality gates (`scripts/check_all.sh`) run on {date}. Long outputs are trimmed to their
summary lines; nothing is rewritten.

## How the hardened agent is safe (and why that matters)

All demo agents call the **same** naive, instruction-following mock model
(`MockLLM(profile="vulnerable")`, see `src/agentguard/llm/mock.py`). The model is never told to
behave: it obeys injected instructions, decodes encoded payloads, repeats its system prompt on
request and calls whatever tools a conversation asks for. The agents differ only in the code
around the model:

| Agent | Defense code |
|---|---|
| `vulnerable_agent.py` | none |
| `partially_hardened_agent.py` | raw-text keyword filter + tool allowlist |
| `hardened_agent.py` | `defenses.py`: input classifier on normalized readings (base64/ROT13/homoglyph/zero-width/leet/split-word/multilingual), plan-then-execute from trusted input only, tool guard (allowlist, argument validation, provenance of destinations, default-deny approval gate, call caps), spotlighting of untrusted content, output filter (secret/system-prompt leakage incl. encoded readings, PII redaction, external-link stripping, active-content neutralization, package verification, length cap), memory-write sanitizer |
| `rag_agent.py` | `agent`: none; `hardened`: classifier + spotlighting + output filter |

So when AgentGuard reports the hardened agent clean and the vulnerable agent failing on the same
cases, the difference is attributable to defense code — which is exactly what an evaluation
framework must be able to see. Ground truth (`examples/ground_truth.yaml`) was written from the
agents' code and never edited to fit results. During development, dataset cases that bypassed the
hardened agent were kept and the *defense code* was improved; one meta-validation false positive
was traced to a case attributing a correct finding to the wrong category and fixed in the dataset
with a new lint rule (DECISIONS.md D-016).
"""


def clean(text: str) -> str:
    lines = [ANSI.sub("", line) for line in text.splitlines()]
    return "\n".join(line for line in lines if not NOISE.search(line))


def split_gates(log: str) -> dict[str, str]:
    parts = re.split(r"^================ gate: (\w+) ================$", log, flags=re.MULTILINE)
    gates: dict[str, str] = {}
    for i in range(1, len(parts) - 1, 2):
        gates[parts[i]] = parts[i + 1].split("================ summary")[0].strip()
    summary = log.split("================ summary ================")
    if len(summary) > 1:
        gates["summary"] = summary[1].strip()
    return gates


def trim(text: str, keep: int = 60, *, pattern: str | None = None) -> str:
    lines = text.splitlines()
    if pattern:
        picked = [line for line in lines if re.search(pattern, line)]
        if picked:
            lines = picked
    if len(lines) > keep:
        lines = [f"... ({len(lines) - keep} earlier lines trimmed) ...", *lines[-keep:]]
    return "\n".join(lines)


SECTIONS = [
    ("summary", "Gate summary", None, 20),
    ("lint", "1. Ruff lint", None, 10),
    ("format", "1b. Ruff format", None, 10),
    ("types", "2. mypy --strict", None, 10),
    (
        "tests",
        "3, 5, 6. Tests (pytest, no network, Hypothesis 200 examples, snapshots) and coverage report",
        r"TOTAL|passed|failed|^agentguard/(detectors|scoring|judges|harness/canary)|Required|skipped",
        80,
    ),
    ("coverage", "4. Coverage gates", None, 40),
    ("audit", "9. pip-audit", None, 40),
    ("secrets", "10. Secret scan", None, 30),
    ("docstrings", "Docstring coverage (interrogate)", None, 20),
    ("datasets", "11. Dataset lint", None, 40),
    ("metavalidate", "12. Meta-validation", None, 40),
    ("determinism", "14. Determinism", None, 20),
    ("mutation", "7. Mutation testing (mutmut)", None, 40),
    ("load", "13. Load test", None, 40),
    ("docker", "15. Docker build + compose healthz", None, 40),
    ("freshclone", "16. Fresh clone + README quickstart", None, 40),
]


def main() -> None:
    log = clean(Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace"))
    gates = split_gates(log)
    out = [INTRO.format(date=datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"))]
    for key, title, pattern, keep in SECTIONS:
        body = gates.get(key)
        if body is None:
            continue
        anchor = key
        out += [f'<a id="{anchor}"></a>', f"## {title}", "", "```text", trim(body, keep, pattern=pattern), "```", ""]
    for extra in sys.argv[2:]:
        path = Path(extra)
        out += [
            f"## {path.stem.replace('_', ' ').capitalize()}",
            "",
            "```text",
            trim(clean(path.read_text(encoding="utf-8", errors="replace")), 80),
            "```",
            "",
        ]
    Path("docs/VALIDATION.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/VALIDATION.md")


if __name__ == "__main__":
    main()
